// Command emojigen builds the data of the Emoji & Symbols extension from Unicode's files:
// emoji-test.txt for the emoji, their order, groups and skin tones, and CLDR's annotations for
// their names and keywords in English and Portuguese, and for other symbols.
//
//	go -C tools run ./emojigen -src DIR -out ../extensions/emoji/data/emoji.tsv
//
// DIR holds emoji-test.txt (unicode.org/Public/emoji/16.0/) and, from cldr-json 46.0.0,
// cldr-annotations-full/annotations/{en,pt}/annotations.json as ann-en.json and ann-pt.json
// and cldr-annotations-derived-full/annotationsDerived/{en,pt}/annotations.json as
// der-en.json and der-pt.json. See extensions/emoji/data/README.md.
package main

import (
	"bufio"
	"encoding/json"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
	"unicode"
)

// annotation is a CLDR annotation: keywords, and the name read out (tts).
type annotation struct {
	Default []string `json:"default"`
	TTS     []string `json:"tts"`
}

// emoji is one row of the output.
type emoji struct {
	chars, group, name string
	tones              [5]string // the five skin tones, when the emoji takes them
}

// components are the emoji that only make up others, as skin tones.
var components = map[string]bool{}

var tones = []string{"light skin tone", "medium-light skin tone", "medium skin tone", "medium-dark skin tone", "dark skin tone"}

func main() {
	src := flag.String("src", "", "the folder of the downloaded files")
	out := flag.String("out", "", "the file to write")
	flag.Parse()
	if *src == "" || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	emojis, err := readTest(filepath.Join(*src, "emoji-test.txt"))
	if err != nil {
		log.Fatal(err)
	}
	en := annotations(*src, "en")
	pt := annotations(*src, "pt")

	f, err := os.Create(*out)
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriter(f)
	fmt.Fprintln(w, "# chars\tgroup\tname en\tkeywords en\tname pt\tkeywords pt\tskin tones")
	fmt.Fprintln(w, "# Generated by tools/emojigen from Unicode emoji-test 16.0 and CLDR 46. Do not edit.")
	known := map[string]bool{}
	row := func(chars, group, fallback string, tones []string) {
		enA, ptA := lookup(en, chars), lookup(pt, chars)
		name := first(enA.TTS, fallback)
		fmt.Fprintf(w, "%s\t%s\t%s\t%s\t%s\t%s\t%s\n", chars, group, name, join(enA.Default, name),
			first(ptA.TTS, name), join(ptA.Default, first(ptA.TTS, "")), strings.Join(tones, ","))
	}
	for _, e := range emojis {
		known[strip(e.chars)] = true
		var ts []string
		if e.tones[0] != "" {
			ts = e.tones[:]
		}
		row(e.chars, e.group, e.name, ts)
	}
	// Symbols that are not emoji, as arrows and math, from CLDR alone.
	var symbols []string
	for chars := range en {
		if !known[strip(chars)] && !components[strip(chars)] && symbol(chars) {
			symbols = append(symbols, chars)
		}
	}
	slices.Sort(symbols)
	for _, s := range symbols {
		row(s, "Text Symbols", s, nil)
	}
	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}
	log.Printf("%d emoji, %d symbols", len(emojis), len(symbols))
}

// readTest reads the fully-qualified emoji, in order, without the Component group, each with
// its skin tone variants.
func readTest(path string) ([]emoji, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []emoji
	byName := map[string]int{}
	group := ""
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if g, ok := strings.CutPrefix(line, "# group: "); ok {
			group = g
			continue
		}
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		codes, rest, ok := strings.Cut(line, ";")
		if group == "Component" {
			components[strip(decode(codes))] = true // hair and skin tones: parts, not emoji
			continue
		}
		if !ok || !strings.HasPrefix(strings.TrimSpace(rest), "fully-qualified") {
			continue
		}
		_, comment, _ := strings.Cut(rest, "#")
		// "# 👋🏽 E1.0 waving hand: medium skin tone"
		fields := strings.SplitN(strings.TrimSpace(comment), " ", 3)
		if len(fields) < 3 {
			continue
		}
		chars, name := decode(codes), fields[2]
		if base, tone, ok := strings.Cut(name, ": "); ok {
			if i := slices.Index(tones, tone); i >= 0 {
				if j, ok := byName[base]; ok {
					out[j].tones[i] = chars
				}
				continue
			}
			if strings.Contains(tone, "skin tone") {
				continue // two people of two tones: too many to offer
			}
		}
		byName[name] = len(out)
		out = append(out, emoji{chars: chars, group: group, name: name})
	}
	// An emoji takes skin tones only when all five exist.
	for i := range out {
		if slices.Contains(out[i].tones[:], "") {
			out[i].tones = [5]string{}
		}
	}
	return out, sc.Err()
}

func decode(codes string) string {
	var b strings.Builder
	for _, c := range strings.Fields(codes) {
		r, err := strconv.ParseUint(c, 16, 32)
		if err != nil {
			log.Fatalf("code %q: %v", c, err)
		}
		b.WriteRune(rune(r))
	}
	return b.String()
}

// annotations reads the plain and derived annotations of a language.
func annotations(dir, lang string) map[string]annotation {
	out := map[string]annotation{}
	for _, name := range []string{"der-" + lang + ".json", "ann-" + lang + ".json"} {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			log.Fatal(err)
		}
		var doc map[string]struct {
			Annotations map[string]annotation `json:"annotations"`
		}
		if err := json.Unmarshal(data, &doc); err != nil {
			log.Fatalf("%s: %v", name, err)
		}
		for _, v := range doc {
			for k, a := range v.Annotations {
				out[k] = a
			}
		}
	}
	return out
}

// lookup finds an emoji's annotation, with or without its variation selector.
func lookup(m map[string]annotation, chars string) annotation {
	if a, ok := m[chars]; ok {
		return a
	}
	return m[strip(chars)]
}

func strip(s string) string { return strings.ReplaceAll(s, "️", "") }

// symbol reports whether a CLDR key is a symbol worth offering: one character that is not a
// letter, digit or plain ASCII punctuation.
func symbol(s string) bool {
	r := []rune(s)
	if len(r) != 1 || r[0] < 0x80 {
		return false
	}
	return !unicode.IsLetter(r[0]) && !unicode.IsDigit(r[0])
}

func first(s []string, fallback string) string {
	if len(s) > 0 && s[0] != "" {
		return s[0]
	}
	return fallback
}

// join lists keywords, without the name itself and without tabs or bars.
func join(words []string, name string) string {
	var out []string
	for _, w := range words {
		w = strings.NewReplacer("\t", " ", "|", " ").Replace(w)
		if w != name && w != "" {
			out = append(out, w)
		}
	}
	return strings.Join(out, "|")
}
